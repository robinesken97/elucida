def set_lang(lang: str):
    global _LANG
    _LANG = "en" if str(lang).lower().startswith("en") else "de"


def get_lang() -> str:
    return _LANG


def T(_key: str, **kw) -> str:
    de, en = TEXTS.get(_key, (_key, _key))
    txt = en if _LANG == "en" else de
    return txt.format(**kw) if kw else txt
